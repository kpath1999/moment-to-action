"""Accuracy evaluation utilities for object detection and image-embedding models.

Implements IoU-based detection metrics (used by YOLO evaluation) and cosine
similarity (used by MobileCLIP embedding consistency evaluation).

Ground truth is generated by a CPU/float32 oracle — the highest-fidelity
variant of each model.  Evaluated variants are compared against that oracle.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import numpy as np

if TYPE_CHECKING:
    from numpy.typing import NDArray


# ---------------------------------------------------------------------------
# Box structure helpers
# ---------------------------------------------------------------------------

# A detection box as a plain array: [x1, y1, x2, y2, score, class_id]
# All coordinates are in the model's *input* coordinate space (before scaling).
DetBox = tuple[float, float, float, float, float, int]  # x1,y1,x2,y2,score,class_id


def compute_iou(box_a: NDArray[np.float32], box_b: NDArray[np.float32]) -> float:
    """Return intersection-over-union of two [x1, y1, x2, y2] boxes."""
    x1 = max(float(box_a[0]), float(box_b[0]))
    y1 = max(float(box_a[1]), float(box_b[1]))
    x2 = min(float(box_a[2]), float(box_b[2]))
    y2 = min(float(box_a[3]), float(box_b[3]))

    inter_w = max(0.0, x2 - x1)
    inter_h = max(0.0, y2 - y1)
    inter = inter_w * inter_h

    if inter == 0.0:
        return 0.0

    area_a = max(0.0, float(box_a[2] - box_a[0])) * max(0.0, float(box_a[3] - box_a[1]))
    area_b = max(0.0, float(box_b[2] - box_b[0])) * max(0.0, float(box_b[3] - box_b[1]))
    union = area_a + area_b - inter
    return inter / union if union > 0.0 else 0.0


# ---------------------------------------------------------------------------
# Per-image detection matching
# ---------------------------------------------------------------------------


def match_detections(
    pred_boxes: list[NDArray[np.float32]],
    gt_boxes: list[NDArray[np.float32]],
    iou_threshold: float = 0.5,
) -> tuple[int, int, int]:
    """Greedy-match predictions to ground truth at a given IoU threshold.

    Returns ``(tp, fp, fn)`` for a single image.

    Each element of *pred_boxes* and *gt_boxes* is a float32 array
    ``[x1, y1, x2, y2]`` in the same coordinate space.
    """
    if not gt_boxes:
        return 0, len(pred_boxes), 0
    if not pred_boxes:
        return 0, 0, len(gt_boxes)

    gt_matched = [False] * len(gt_boxes)
    tp = fp = 0

    for pred in pred_boxes:
        best_iou = 0.0
        best_j = -1
        for j, gt in enumerate(gt_boxes):
            if gt_matched[j]:
                continue
            iou = compute_iou(pred, gt)
            if iou > best_iou:
                best_iou = iou
                best_j = j

        if best_iou >= iou_threshold and best_j >= 0:
            gt_matched[best_j] = True
            tp += 1
        else:
            fp += 1

    fn = gt_matched.count(False)
    return tp, fp, fn


# ---------------------------------------------------------------------------
# mAP50 — averaged over a collection of images
# ---------------------------------------------------------------------------


def compute_map50(
    pred_per_image: list[list[NDArray[np.float32]]],
    gt_per_image: list[list[NDArray[np.float32]]],
) -> float:
    """Return mean precision@IoU=0.5 over a set of images.

    Args:
        pred_per_image: One list of ``[x1,y1,x2,y2]`` arrays per image.
        gt_per_image:   Corresponding ground-truth box lists.

    Returns:
        Float in [0, 1]; 1.0 when predictions perfectly match oracle labels.
        Returns 0.0 when there are no predictions and no GT boxes.
    """
    if len(pred_per_image) != len(gt_per_image):
        msg = "pred_per_image and gt_per_image must have the same length"
        raise ValueError(msg)

    total_tp = total_fp = total_fn = 0
    for pred_boxes, gt_boxes in zip(pred_per_image, gt_per_image, strict=True):
        tp, fp, fn = match_detections(pred_boxes, gt_boxes, iou_threshold=0.5)
        total_tp += tp
        total_fp += fp
        total_fn += fn

    precision = total_tp / (total_tp + total_fp) if (total_tp + total_fp) > 0 else 0.0
    recall = total_tp / (total_tp + total_fn) if (total_tp + total_fn) > 0 else 0.0

    # F1-like harmonic mean (balanced metric that rewards high P and R together)
    if precision + recall == 0.0:
        return 0.0
    return 2.0 * precision * recall / (precision + recall)


# ---------------------------------------------------------------------------
# Embedding consistency (MobileCLIP)
# ---------------------------------------------------------------------------


def cosine_similarity(a: NDArray[np.float32], b: NDArray[np.float32]) -> float:
    """Return cosine similarity between two 1-D vectors."""
    a_flat = a.ravel().astype(np.float64)
    b_flat = b.ravel().astype(np.float64)
    norm_a = float(np.linalg.norm(a_flat))
    norm_b = float(np.linalg.norm(b_flat))
    if norm_a == 0.0 or norm_b == 0.0:
        return 0.0
    return float(np.dot(a_flat, b_flat) / (norm_a * norm_b))


def mean_embedding_similarity(
    oracle_outputs: list[NDArray[np.float32]],
    eval_outputs: list[NDArray[np.float32]],
) -> float:
    """Return mean cosine similarity between paired oracle and eval embeddings.

    A score of 1.0 means the evaluated variant produces identical embeddings
    to the CPU/float32 oracle. Values near 1 indicate high quantization fidelity.
    """
    if len(oracle_outputs) != len(eval_outputs):
        msg = "oracle_outputs and eval_outputs must have the same length"
        raise ValueError(msg)
    if not oracle_outputs:
        return 0.0
    sims = [cosine_similarity(o, e) for o, e in zip(oracle_outputs, eval_outputs, strict=True)]
    return float(np.mean(sims))


# ---------------------------------------------------------------------------
# YOLO output parsing (standalone, no Stage dependency)
# ---------------------------------------------------------------------------


def _nms(
    boxes: NDArray[np.float32],
    scores: NDArray[np.float32],
    iou_threshold: float = 0.45,
) -> list[int]:
    """Pure-numpy NMS — same logic as YOLOStage._nms."""
    indices = np.argsort(scores)[::-1]
    keep: list[int] = []
    while len(indices) > 0:
        current = int(indices[0])
        keep.append(current)
        if len(indices) == 1:
            break
        rest = indices[1:]
        ious = np.array(
            [compute_iou(boxes[current], boxes[r]) for r in rest],
            dtype=np.float64,
        )
        indices = rest[ious < iou_threshold]
    return keep


def parse_yolo_outputs(
    outputs: list[NDArray[np.float32]],
    confidence_threshold: float = 0.25,
) -> list[NDArray[np.float32]]:
    """Parse raw YOLO model outputs into a list of ``[x1,y1,x2,y2]`` boxes.

    Handles both the 1-tensor (``[1,84,N]``) and 3-tensor (boxes/scores/ids)
    output formats.  Coordinates remain in model input space (640 or 320 px).

    Args:
        outputs: Raw output tensors from ``backend.run()``.
        confidence_threshold: Minimum confidence for a detection to survive.

    Returns:
        List of float32 arrays ``[x1, y1, x2, y2]`` for surviving detections.
    """
    if len(outputs) == 1:
        raw = outputs[0]
        _n_cols = 84
        data = raw[0]
        if data.shape[0] == _n_cols:
            data = data.T  # [N, 84]
        if data.ndim != 2 or data.shape[1] != _n_cols:  # noqa: PLR2004
            return []
        cxcywh = data[:, :4].astype(np.float32)
        class_scores = data[:, 4:].astype(np.float32)
        scores = class_scores.max(axis=1)
        mask = scores >= confidence_threshold
        cxcywh, scores = cxcywh[mask], scores[mask]
        if len(cxcywh) == 0:
            return []
        x1 = cxcywh[:, 0] - cxcywh[:, 2] / 2
        y1 = cxcywh[:, 1] - cxcywh[:, 3] / 2
        x2 = cxcywh[:, 0] + cxcywh[:, 2] / 2
        y2 = cxcywh[:, 1] + cxcywh[:, 3] / 2
        boxes_raw = np.stack([x1, y1, x2, y2], axis=1)
    elif len(outputs) >= 3:  # noqa: PLR2004
        boxes_raw = outputs[0][0].astype(np.float32)  # [N,4]
        scores = outputs[1][0].astype(np.float32)
        mask = scores >= confidence_threshold
        boxes_raw, scores = boxes_raw[mask], scores[mask]
        if len(boxes_raw) == 0:
            return []
    else:
        return []

    keep = _nms(boxes_raw, scores, iou_threshold=0.45)
    return [boxes_raw[i] for i in keep]
